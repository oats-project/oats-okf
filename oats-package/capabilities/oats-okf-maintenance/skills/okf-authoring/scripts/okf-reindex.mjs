#!/usr/bin/env node
/**
 * okf-reindex.mjs — the subject layout's generated views (no dependencies).
 *
 * Usage: node okf-reindex.mjs <bundle-dir> [--check] [--json]
 *
 * A base is bridged when its okf-base.json (version 1) lists the reserved nodes
 * `claims`, `subjects` and `verdicts`, each at the path of its name and owned by
 * the sentinel 00000000-0000-0000-0000-000000000000. On a bridged base this
 * writes, deterministically, from the frontmatter of every concept:
 *   subjects/<kind>/<slug>/index.md   one section per claim type (`about:`)
 *   subjects/index.md                 the subjects by kind
 *   verdicts/index.md                 the verdict record, one line per verdict
 *   index.md                          its "## Subjects" section only
 * --check writes nothing and exits 1 when any of them differs.
 * It refuses (exit 2, E_PATH) a base holding a symlink, a non-regular file or a
 * multiply-linked file, before reading or writing anything.
 * Exit: 0 written or clean, 1 stale (--check), 2 usage, refusal or not a bridged base.
 *
 * The validator imports this module, so the views it checks are exactly the
 * ones written here, and consult parses them with the parsers below.
 */
import { createHash, randomBytes } from "node:crypto";
import { closeSync, constants as fsConstants, existsSync, fstatSync, lstatSync, mkdirSync, openSync, readFileSync, readdirSync, realpathSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { join, relative, resolve, dirname, sep } from "node:path";
import { fileURLToPath } from "node:url";

export const SENTINEL = "00000000-0000-0000-0000-000000000000";
export const RESERVED_NODES = ["claims", "subjects", "verdicts"];
export const KINDS = { system: "System", workstream: "Workstream", project: "Project" };
export const KIND_HEADINGS = { system: "Systems", workstream: "Workstreams", project: "Projects" };
export const VERDICTS = ["rejected", "superseded", "duplicate"];
export const GENERATED_NOTE = "Generated by okf-reindex.mjs; do not edit by hand.";
const MEMBERS = "In this workstream";

// ------------------------------------------------------------- frontmatter
/** A flow list `[a, "b"]`: bare or JSON double-quoted items; null when the
 *  value is not one (nested or unbalanced brackets, an empty item). */
export function flowList(value) {
  // One cursor pass, no backtracking: the parser also runs on plain bases.
  const s = value.slice(1, -1), items = [], space = (c) => c === " " || c === "\t" || c === "\r" || c === "\n";
  let i = 0;
  const skip = () => { while (i < s.length && space(s[i])) i++; };
  skip();
  if (i === s.length) return [];
  for (;;) {
    skip();
    if (i >= s.length) return null; // an empty item
    if (s[i] === '"') {
      let j = i + 1;
      while (j < s.length && s[j] !== '"') j += s[j] === "\\" ? 2 : 1;
      if (j >= s.length) return null;
      try { items.push(JSON.parse(s.slice(i, j + 1))); } catch { return null; }
      i = j + 1;
    } else {
      const from = i;
      while (i < s.length && s[i] !== ",") { if (s[i] === '"' || s[i] === "[" || s[i] === "]") return null; i++; }
      const bare = s.slice(from, i).trim();
      if (!bare) return null;
      items.push(bare);
    }
    skip();
    if (i >= s.length) return items;
    if (s[i] !== ",") return null;
    i++;
  }
}
/** A flow-list value without its trailing comment: ` #` outside double quotes. */
function listValue(value) {
  let quoted = false;
  for (let i = 0; i < value.length; i++) {
    const c = value[i];
    if (quoted && c === "\\") { i++; continue; }
    if (c === '"') quoted = !quoted;
    else if (!quoted && c === "#" && i > 0 && /\s/.test(value[i - 1])) return value.slice(0, i).trim();
  }
  return value.trim();
}
/** A scalar exactly as 5.8 read it, `value.replace(/\s+#.*$/, "")` then the
 *  outer quotes and trim, in one linear pass: that regex backtracks
 *  quadratically over a long whitespace run with no `#` after it. Its match
 *  is the whitespace run before the first `#` that follows whitespace and has
 *  no line terminator after it (`.` stops at \r, \u2028 and \u2029). */
export function scalarValue(value) {
  let cut = value.length;
  let last = -1;
  for (let i = value.length - 1; i >= 0; i--) if (/[\n\r\u2028\u2029]/.test(value[i])) { last = i; break; }
  for (let j = Math.max(last + 1, 1); j < value.length; j++) {
    if (value[j] !== "#" || !/\s/.test(value[j - 1])) continue;
    let i = j - 1;
    while (i > 0 && /\s/.test(value[i - 1])) i--;
    cut = i; break;
  }
  return value.slice(0, cut).replace(/^["']|["']$/g, "").trim();
}
/** Where the bracket opened at 0 closes (outside double quotes), or -1 when
 *  it never does: `[a, [b] junk` is unclosed, `[WIP] title` closes at 4. */
function closesAt(value) {
  let depth = 0, quoted = false;
  for (let i = 0; i < value.length; i++) {
    const c = value[i];
    if (quoted) { if (c === "\\") i++; else if (c === '"') quoted = false; continue; }
    if (c === '"') quoted = true;
    else if (c === "[") depth++;
    else if (c === "]" && --depth === 0) return i;
  }
  return -1;
}
/** A `key: value` line as 5.8's `/^([A-Za-z_][A-Za-z0-9_-]*):\s*(.*)$/` read
 *  it, in linear time: the value is what follows the colon and its leading
 *  whitespace (greedy `\s*`, which also takes \r, U+2028 and U+2029), and the
 *  line does not match when that value still holds a terminator `.` does not
 *  match. (The regex backtracks quadratically over long whitespace followed
 *  by such a terminator.) */
export function keyValue(line) {
  const key = line.match(/^[A-Za-z_][A-Za-z0-9_-]*:/);
  if (!key) return null;
  const value = line.slice(key[0].length).trimStart();
  if (/[\r\u2028\u2029]/.test(value)) return null;
  return [line, key[0].slice(0, -1), value];
}
/** The OKF frontmatter subset: flat `key: scalar` lines and flow lists.
 *  `listErrors` names keys whose value looks like a list but is not one. */
export function parseFrontmatter(text) {
  if (!text.startsWith("---")) return { present: false };
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---(\r?\n|$)/);
  if (!m) return { present: true, parsed: false };
  const meta = {}, listErrors = [];
  for (const line of m[1].split("\n")) {
    if (/^\s*#/.test(line) || !line.trim()) continue;
    const kv = keyValue(line);
    if (!kv) { if (!/^\s+/.test(line)) return { present: true, parsed: false }; continue; }
    // A value starting with `[` is a flow list: its comment is stripped outside
    // quotes, and an unclosed one (no `]` at all) is malformed. A bracketed
    // scalar such as `[WIP] title` (a `]` but not at the end) stays a scalar,
    // read as 5.8 read every value.
    let list;
    if (/^\s*\[/.test(kv[2])) {
      const v = listValue(kv[2]), closed = closesAt(v);
      // A list unless the first close is followed by text (`[WIP] title`):
      // `[a, b]]` or `[a, b],` is a malformed list, not a scalar.
      if (closed < 0) list = null;
      else if (/^[\s\],]*$/.test(v.slice(closed + 1))) list = flowList(v);
    }
    if (list === null) listErrors.push(kv[1]);
    meta[kv[1]] = Array.isArray(list) ? list : scalarValue(kv[2]);
  }
  return { present: true, parsed: true, meta, listErrors, body: text.slice(m[0].length) };
}

// ------------------------------------------------------------- layout
/** Whether a parsed okf-base.json declares the subject layout. All three
 *  reserved nodes, exactly; anything less is a plain version-1 base. */
export function isBridgedMeta(m) {
  if (!m || typeof m !== "object" || m.version !== 1 || !m.nodes || typeof m.nodes !== "object") return false;
  return RESERVED_NODES.every((n) => Object.hasOwn(m.nodes, n) && m.nodes[n]?.path === n && m.nodes[n]?.owner === SENTINEL);
}
/** Whether the base at root declares the subject layout: false when it has
 *  no okf-base.json or one that is not valid JSON (every consumer refuses that
 *  base on its own). okf-base.json is read only as a regular single-link file,
 *  never through a link or from a FIFO, and never above METADATA_LIMIT;
 *  anything else is refused (E_PATH, E_TOO_LARGE), so no reader can see a
 *  layout another reader does not. */
/** The one size limit every reader applies to okf-base.json (the validator,
 *  the regenerator, propose and consult): above it the metadata is refused,
 *  never read as a plain base by one reader and a bridged one by another. */
export const METADATA_LIMIT = 16 * 1024 * 1024;
export const metadataTooLarge = () => Object.assign(new Error(`okf-base.json is larger than ${METADATA_LIMIT} bytes; base metadata is a short JSON document`), { code: "E_TOO_LARGE" });
export function bridged(root) {
  const file = join(root, "okf-base.json");
  const unsafe = (why) => { throw Object.assign(new Error(`okf-base.json: ${why}; the base metadata must be a regular single-link file`), { code: "E_PATH" }); };
  let st;
  try { st = lstatSync(file); } catch (e) { if (e.code === "ENOENT") return false; throw e; }
  if (!st.isFile()) unsafe(st.isSymbolicLink() ? "a symlink" : "not a regular file");
  if (st.nlink !== 1) unsafe("a file with more than one link");
  if (st.size > METADATA_LIMIT) throw metadataTooLarge();
  const fd = openSync(file, fsConstants.O_RDONLY | fsConstants.O_NOFOLLOW | fsConstants.O_NONBLOCK);
  let text;
  try {
    const opened = fstatSync(fd);
    if (!opened.isFile() || opened.ino !== st.ino || opened.dev !== st.dev) unsafe("replaced while it was opened");
    if (opened.size > METADATA_LIMIT) throw metadataTooLarge();
    text = readFileSync(fd, "utf8");
  } finally { closeSync(fd); }
  try { return isBridgedMeta(JSON.parse(text)); } catch { return false; }
}
export const subjectRef = (kind, slug) => `${kind}/${slug}`;
/** subjects/<kind>/<slug>.md → { kind, slug, ref }, else null. */
export function subjectOfPath(p) {
  const m = /^subjects\/([^/]+)\/([^/]+)\.md$/.exec(p);
  return m && Object.hasOwn(KINDS, m[1]) && m[2] !== "index" && m[2] !== "log" ? { kind: m[1], slug: m[2], ref: subjectRef(m[1], m[2]) } : null;
}
export const subjectFile = (ref) => `subjects/${ref}.md`;
export const viewFile = (ref) => `subjects/${ref}/index.md`;
export const SUBJECT_REF = /^(system|workstream|project)\/[a-z0-9][a-z0-9._-]*$/;
/** Where a concept lives in the layout: a subject file, a verdict, or a claim
 *  (anything else: claims/** and every old node). */
export function place(p) {
  if (p.startsWith("subjects/")) return "subjects";
  if (p.startsWith("verdicts/")) return "verdicts";
  return "claim";
}
/** The claim type a concept's `type` maps to (design §2.2): the bridge keeps
 *  each file's legacy `type` and its `kind`, and the layer reads Lesson,
 *  Conclusion and Limitation as Insight and Roadmap as Decision. */
export const LEGACY_TYPES = { Lesson: ["Insight", "lesson"], Conclusion: ["Insight", "finding"], Limitation: ["Insight", "constraint"], Roadmap: ["Decision", "direction"] };
export function claimType(type, kind) {
  const t = String(type ?? "").trim(), k = typeof kind === "string" ? kind.trim() : "";
  const mapped = Object.hasOwn(LEGACY_TYPES, t) ? LEGACY_TYPES[t] : null;
  return { type: mapped ? mapped[0] : t, kind: k || (mapped ? mapped[1] : "") };
}
/** sha256 of `<Type>|<title>` (the mapped claim type), the title lowercased, trimmed and its
 *  whitespace collapsed; 16 hex. A candidate key, never an identity. */
export function titleHash(type, title) {
  const norm = String(title ?? "").toLowerCase().trim().replace(/\s+/g, " ");
  return createHash("sha256").update(`${claimType(type).type}|${norm}`).digest("hex").slice(0, 16);
}

// ------------------------------------------------------------- render
const one = (s) => String(s ?? "").replace(/\s+/g, " ").trim();
// Brackets would end the link text for every reader's link pattern (the 5.8
// validator's included), leaving the claim unlinked: shown as parentheses.
const linkText = (s) => one(s).replace(/\[/g, "(").replace(/\]/g, ")");
// Frontmatter prose (a description, a type or kind heading, a subject title)
// moves into a generated index, where a link it holds would resolve against
// the index, not its concept: rendered as plain text, brackets as parentheses,
// so no reader (the 5.8 validator included) sees a link.
export const plainText = linkText;
function entry(title, path, description) {
  // Consult resolves a link by cutting `?` and `#` and decoding `%`, so a path
  // holding one would read a different file: such a path is never linked.
  if (/[\s()<>?#%\\]/.test(path)) throw Object.assign(new Error(`${path}: a path with spaces, parentheses, angle brackets, ?, #, % or \\ cannot be linked from a generated index (a reader would resolve it to another file)`), { code: "E_PATH" });
  const d = plainText(description);
  return `* [${linkText(title)}](/${path})${d ? ` - ${d}` : ""}`;
}
const fallbackTitle = (p) => p.split("/").pop().replace(/\.md$/, "");
const byText = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

/** Every generated file's expected content, from the concepts' frontmatter
 *  (`concepts`: Map of base path → meta, reserved files excluded) and the
 *  current root index.md text. → Map of base path → text. */
/** The Map/Set key for text read from a base or a committed index (untrusted).
 *  V8 hashes a string longer than 16383 characters by its length alone, so
 *  many long keys of one length make each insertion compare against all the
 *  others (quadratic); such text is keyed by its sha256 instead, computed once.
 *  The two forms are tagged ("=" text, "#" digest) so no text keys like
 *  another's digest. */
export const KEY_CHARS = 16000;
export const textKey = (text) => text.length <= KEY_CHARS ? `=${text}` : `#${createHash("sha256").update(text).digest("hex")}`;
export function generate(concepts, rootIndex = "") {
  const subjects = new Map();
  for (const [p, meta] of concepts) {
    const s = subjectOfPath(p);
    if (s) subjects.set(s.ref, { ...s, path: p, meta: meta || {} });
  }
  const out = new Map();
  // Subject views.
  const claimsOf = new Map([...subjects.keys()].map((ref) => [ref, []]));
  for (const [p, meta] of [...concepts].sort(([a], [b]) => byText(a, b))) {
    if (place(p) !== "claim" || !Array.isArray(meta?.about)) continue;
    // Only this base's subject refs are keyed (a long untrusted item is never one).
    for (const ref of new Set(meta.about.filter((r) => claimsOf.has(r)))) claimsOf.get(ref).push({ path: p, meta });
  }
  const order = (ref) => Object.keys(KINDS).indexOf(ref.split("/")[0]);
  const sortedRefs = [...subjects.keys()].sort((a, b) => order(a) - order(b) || byText(a, b));
  // Each workstream's members, in sortedRefs order, from one pass over the
  // subjects (the validator runs this on bases it does not trust).
  const membersOf = new Map();
  for (const r of sortedRefs) {
    const list = subjects.get(r).meta["in-workstreams"];
    if (Array.isArray(list)) for (const w of new Set(list.filter((x) => subjects.has(x)))) if (w !== r) { if (!membersOf.has(w)) membersOf.set(w, []); membersOf.get(w).push(r); }
  }
  for (const ref of sortedRefs) {
    const s = subjects.get(ref), title = plainText(s.meta.title) || s.slug;
    const lines = [`# ${title}`, ""];
    if (plainText(s.meta.description)) lines.push(plainText(s.meta.description), "");
    lines.push(GENERATED_NOTE, `Subject file: [${linkText(title)}](/${s.path})`, "");
    if (s.kind === "workstream") {
      const members = membersOf.get(ref) ?? [];
      if (members.length) {
        lines.push(`## ${MEMBERS}`, "");
        for (const r of members) lines.push(entry(one(subjects.get(r).meta.title) || subjects.get(r).slug, subjects.get(r).path, subjects.get(r).meta.description));
        lines.push("");
      }
    }
    // type → kind → entries, keyed by textKey (types and kinds are free text).
    const types = new Map();
    for (const c of claimsOf.get(ref)) {
      const mapped = claimType(typeof c.meta.type === "string" ? one(c.meta.type) : "", typeof c.meta.kind === "string" ? one(c.meta.kind) : "");
      const type = plainText(mapped.type) || "Untyped", kind = plainText(mapped.kind), tk = textKey(type), kk = textKey(kind);
      if (!types.has(tk)) types.set(tk, { type, kinds: new Map() });
      const kinds = types.get(tk).kinds;
      if (!kinds.has(kk)) kinds.set(kk, { kind, entries: [] });
      kinds.get(kk).entries.push(entry(one(c.meta.title) || fallbackTitle(c.path), c.path, c.meta.description));
    }
    if (!types.size) lines.push("No claims are about this subject yet.", "");
    for (const { type, kinds } of [...types.values()].sort((a, b) => byText(a.type, b.type))) {
      lines.push(`## ${type}`, "");
      if (kinds.has(textKey(""))) lines.push(...kinds.get(textKey("")).entries, "");
      for (const { kind, entries } of [...kinds.values()].filter((k) => k.kind).sort((a, b) => byText(a.kind, b.kind))) lines.push(`### ${kind}`, "", ...entries, "");
    }
    out.set(viewFile(ref), lines.join("\n").replace(/\n+$/, "") + "\n");
  }
  // subjects/index.md
  const idx = ["# Subjects", "", `${GENERATED_NOTE} What this base's knowledge is about, by kind. Each subject's claims are listed in its generated index, \`subjects/<kind>/<slug>/index.md\`.`, ""];
  for (const kind of Object.keys(KINDS)) {
    const refs = sortedRefs.filter((r) => subjects.get(r).kind === kind);
    if (!refs.length) continue;
    idx.push(`## ${KIND_HEADINGS[kind]}`, "", ...refs.map((r) => entry(one(subjects.get(r).meta.title) || subjects.get(r).slug, subjects.get(r).path, subjects.get(r).meta.description)), "");
  }
  if (!subjects.size) idx.push("No subjects yet.", "");
  out.set("subjects/index.md", idx.join("\n").replace(/\n+$/, "") + "\n");
  // verdicts/index.md
  const verdicts = [...concepts].filter(([p]) => place(p) === "verdicts").sort(([a], [b]) => byText(a, b));
  const vidx = ["# Verdicts", "", `${GENERATED_NOTE} The knowledge maintainer's record of the claims it rejected, superseded or closed as duplicates, one line each: verdict; claim type; title hash; claim description. \`oats okf verdicts --check <claim file>\` reads it.`, ""];
  for (const [p, meta] of verdicts) {
    const fields = [one(meta?.verdict), one(meta?.["claim-type"]), one(meta?.["title-hash"]), one(meta?.["claim-description"])];
    vidx.push(entry(one(meta?.["claim-title"]) || fallbackTitle(p), p, fields.join("; ")));
  }
  if (!verdicts.length) vidx.push("No verdicts yet.");
  out.set("verdicts/index.md", vidx.join("\n").replace(/\n+$/, "") + "\n");
  out.set("index.md", withSubjectsSection(rootIndex));
  return out;
}
export const ROOT_SECTION = "## Subjects\n\n* [Subjects](subjects/index.md) - What this base's knowledge is about, by kind; each subject has a generated index of its claims.\n";
/** The root index.md with its "## Subjects" section (heading to the next
 *  `## ` heading or the end) replaced by the generated one, or appended. */
export function withSubjectsSection(text) {
  const lines = String(text ?? "").replace(/\r\n/g, "\n").split("\n");
  const start = lines.findIndex((l) => /^## Subjects\s*$/.test(l));
  let before, after;
  if (start < 0) { before = lines.join("\n"); after = ""; }
  else {
    let end = lines.findIndex((l, i) => i > start && /^## /.test(l));
    if (end < 0) end = lines.length;
    before = lines.slice(0, start).join("\n");
    after = lines.slice(end).join("\n");
  }
  before = before.replace(/\n+$/, "");
  after = after.replace(/^\n+/, "").replace(/\n+$/, "");
  return `${before ? `${before}\n\n` : ""}${ROOT_SECTION}${after ? `\n${after}\n` : ""}`;
}

// ------------------------------------------------------------- parse (consult)
const ENTRY = /^\* \[([^\]]*)\]\(\/([^)\s]+)\)(?: - (.*))?$/;
export function parseEntry(line) {
  const m = ENTRY.exec(line);
  return m ? { title: m[1], path: m[2], description: m[3] ?? "" } : null;
}
/** A generated subject view → { title, description, members, sections:
 *  [{ type, kind, typeKey, kindKey, entries }] } (kind null for entries
 *  directly under a type; the keys are textKey of each). Members are the
 *  subject-file entries under the membership heading: a claim type spelled
 *  like that heading stays a claim section. */
export function parseView(text) {
  const lines = String(text).split(/\r?\n/), out = { title: "", description: "", members: [], sections: [] };
  let type = null, kind = null, typeKey = null, kindKey = null, inMembers = false;
  const byType = new Map();
  let current = null;
  // The preamble is fixed: `# title`, blank, [description, blank], the
  // generated note, `Subject file: ...`. Read by position, so a description
  // starting with `#` or reading like the note stays the description.
  let body = 0;
  if (lines[0]?.startsWith("# ")) {
    out.title = lines[0].slice(2).trim();
    const noteAt = (i) => lines[i] === GENERATED_NOTE && /^Subject file: /.test(lines[i + 1] ?? "");
    if (noteAt(2)) body = 3;
    else if (lines[1] === "" && lines[3] === "" && noteAt(4)) { out.description = lines[2].trim(); body = 5; }
    else body = 1;
  }
  for (let i = body; i < lines.length; i++) {
    const line = lines[i];
    const h2 = /^## (.+)$/.exec(line), h3 = /^### (.+)$/.exec(line);
    if (h2) { type = h2[1].trim(); typeKey = textKey(type); inMembers = type === MEMBERS; kind = null; kindKey = null; current = null; continue; }
    if (h3) { kind = h3[1].trim(); kindKey = textKey(kind); current = null; continue; }
    const e = parseEntry(line);
    if (!e) continue;
    if (inMembers && kind === null && subjectOfPath(e.path)) out.members.push(e);
    else if (type) {
      // A committed index is untrusted: the section is looked up once per
      // heading, never per entry (no scan of the sections seen so far, no
      // heading-sized key per entry); out.sections keeps first-seen order.
      if (!current) {
        if (!byType.has(typeKey)) byType.set(typeKey, new Map());
        const kinds = byType.get(typeKey);
        current = kinds.get(kindKey);
        if (!current) { out.sections.push(current = { type, kind, typeKey, kindKey, entries: [] }); kinds.set(kindKey, current); }
      }
      current.entries.push(e);
    }
  }
  return out;
}
/** Claim counts by type from a parsed view, in view order: [[type, n], ...]. */
export function counts(view) {
  const out = new Map();
  for (const s of view.sections) {
    const c = out.get(s.typeKey);
    if (c) c[1] += s.entries.length; else out.set(s.typeKey, [s.type, s.entries.length]);
  }
  return [...out.values()];
}
/** subjects/index.md → [{ ref, kind, slug, title, description }]. */
export function parseSubjectsIndex(text) {
  const out = [];
  for (const line of String(text).split(/\r?\n/)) {
    const e = parseEntry(line), s = e && subjectOfPath(e.path);
    if (s) out.push({ ref: s.ref, kind: s.kind, slug: s.slug, title: e.title, description: e.description });
  }
  return out;
}
/** verdicts/index.md → [{ id, path, title, verdict, claimType, titleHash, description }]. */
export function parseVerdictsIndex(text) {
  const out = [];
  for (const line of String(text).split(/\r?\n/)) {
    const e = parseEntry(line), m = e && /^verdicts\/([^/]+)\.md$/.exec(e.path);
    if (!m) continue;
    const [verdict = "", claimType = "", hash = "", ...rest] = e.description.split("; ");
    out.push({ id: m[1], path: e.path, title: e.title, verdict, claimType, titleHash: hash, description: rest.join("; ") });
  }
  return out;
}

// ------------------------------------------------------------- files
/** Every .md file under root (dot entries skipped), as base paths. */
export function markdownFiles(root) {
  const files = [];
  (function walk(d) {
    for (const e of readdirSync(d, { withFileTypes: true })) {
      if (e.name.startsWith(".")) continue;
      const p = join(d, e.name);
      if (e.isDirectory()) walk(p);
      // Only the native separator becomes `/`; a `\\` in a name is refused by
      // assertSafeTree and never turned into a path segment.
      else if (e.name.endsWith(".md")) files.push(relative(root, p).split(sep).join("/"));
    }
  })(root);
  return files.sort(byText);
}
export const isReservedFile = (p) => ["index.md", "log.md"].includes(p.split("/").pop());
/** The concepts' frontmatter (reserved files excluded). */
export function readConcepts(root) {
  const concepts = new Map();
  for (const p of markdownFiles(root)) {
    if (isReservedFile(p)) continue;
    const file = resolve(root, p);
    if (!file.startsWith(root.endsWith(sep) ? root : root + sep)) throw Object.assign(new Error(`${p}: outside the base`), { code: "E_PATH" });
    const fm = parseFrontmatter(readFileSync(file, "utf8"));
    concepts.set(p, fm.parsed ? fm.meta : {});
  }
  return concepts;
}
/** Generated view files on disk that no subject file backs any more. */
export function orphanViews(root, concepts) {
  const out = [];
  for (const p of markdownFiles(root)) {
    const m = /^subjects\/([^/]+)\/([^/]+)\/index\.md$/.exec(p);
    if (m && Object.hasOwn(KINDS, m[1]) && !concepts.has(`subjects/${m[1]}/${m[2]}.md`)) out.push(p);
  }
  return out;
}
/** Before reading or writing a base: every entry under root (dot entries
 *  aside, as everywhere in OKF) is a plain directory or a regular file with
 *  one link, so no write can follow a symlink or a hardlink out of the base. */
export function assertSafeTree(root) {
  const bad = (p, why) => { throw Object.assign(new Error(`${relative(root, p) || "."}: ${why}; generated indexes are read and written only in plain directories and regular single-link files`), { code: "E_PATH" }); };
  const st = lstatSync(root);
  if (!st.isDirectory()) bad(root, "the base root is not a directory");
  (function walk(d) {
    for (const e of readdirSync(d)) {
      if (e.startsWith(".")) continue;
      const p = join(d, e), s = lstatSync(p);
      if (e.includes("\\")) bad(p, "a name with a backslash (not a base path)");
      if (s.isSymbolicLink()) bad(p, "a symlink");
      else if (s.isDirectory()) walk(p);
      else if (!s.isFile()) bad(p, "not a regular file");
      else if (s.nlink !== 1) bad(p, "a file with more than one link");
    }
  })(root);
}
/** Write one generated file under root: its parent directories are created
 *  or checked one plain directory at a time, and the bytes land through a
 *  fresh temporary file renamed over the target (a rename replaces a link, it
 *  never follows one). Call assertSafeTree(root) first. */
export function writeInBase(root, p, text) {
  const parts = p.split("/");
  if (parts.some((x) => !x || x === "." || x === ".." || x.startsWith("."))) throw Object.assign(new Error(`${p}: not a base path`), { code: "E_PATH" });
  let dir = root;
  for (const part of parts.slice(0, -1)) {
    dir = join(dir, part);
    let s; try { s = lstatSync(dir); } catch (e) { if (e.code !== "ENOENT") throw e; mkdirSync(dir); continue; }
    if (!s.isDirectory() || s.isSymbolicLink()) throw Object.assign(new Error(`${relative(root, dir)}: not a plain directory`), { code: "E_PATH" });
  }
  const temp = join(dir, `.okf-reindex-${randomBytes(8).toString("hex")}`);
  writeFileSync(temp, text, { flag: "wx", mode: 0o644 });
  try { renameSync(temp, join(dir, parts[parts.length - 1])); } catch (e) { rmSync(temp, { force: true }); throw e; }
}
const readOr = (file) => (existsSync(file) ? readFileSync(file, "utf8") : null);
/** What --check reports: [{ path, status: missing | stale | orphan }]. */
export function staleViews(root, concepts = readConcepts(root)) {
  const expected = generate(concepts, readOr(join(root, "index.md")) ?? "");
  const out = [];
  for (const [p, text] of expected) {
    const have = readOr(join(root, p));
    if (have === null) out.push({ path: p, status: "missing" });
    else if (have !== text) out.push({ path: p, status: "stale" });
  }
  for (const p of orphanViews(root, concepts)) out.push({ path: p, status: "orphan" });
  return out;
}

function main(argv) {
  const check = argv.includes("--check"), asJson = argv.includes("--json");
  const dir = argv.find((a) => !a.startsWith("--"));
  const unknown = argv.filter((a) => a.startsWith("--") && !["--check", "--json"].includes(a));
  if (!dir || !existsSync(dir) || unknown.length) { console.error("usage: okf-reindex.mjs <bundle-dir> [--check] [--json]"); return 2; }
  const root = realpathSync(resolve(dir));
  let layout;
  try { assertSafeTree(root); layout = bridged(root); } catch (e) { console.error(`okf-reindex: ${e.code ? `${e.code}: ` : ""}${e.message}`); return 2; }
  if (!layout) {
    const message = `${root} has no subject layout: okf-base.json does not list the reserved nodes ${RESERVED_NODES.join(", ")} (owner ${SENTINEL})`;
    if (asJson) console.log(JSON.stringify({ bundle: root, bridged: false, error: message })); else console.error(message);
    return 2;
  }
  let concepts, stale;
  try {
    assertSafeTree(root);
    concepts = readConcepts(root); stale = staleViews(root, concepts);
    if (!check) {
      const expected = generate(concepts, readOr(join(root, "index.md")) ?? "");
      for (const s of stale) {
        const file = join(root, s.path);
        if (s.status === "orphan") {
          rmSync(file);
          try { if (!readdirSync(dirname(file)).length) rmSync(dirname(file), { recursive: true }); } catch { /* best effort */ }
        } else writeInBase(root, s.path, expected.get(s.path));
      }
    }
  } catch (e) { console.error(`okf-reindex: ${e.code ? `${e.code}: ` : ""}${e.message}`); return 2; }
  if (asJson) console.log(JSON.stringify({ bundle: root, bridged: true, check, changed: stale }, null, 2));
  else {
    console.log(`OKF reindex — ${root}`);
    for (const s of stale) console.log(`  ${check ? s.status.padEnd(7) : (s.status === "orphan" ? "removed" : "wrote  ")} ${s.path}`);
    console.log(stale.length ? (check ? `STALE — ${stale.length} generated file(s) differ; run okf-reindex.mjs ${dir}` : `wrote ${stale.length} file(s)`) : "clean — generated indexes are current");
  }
  return check && stale.length ? 1 : 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = main(process.argv.slice(2));
