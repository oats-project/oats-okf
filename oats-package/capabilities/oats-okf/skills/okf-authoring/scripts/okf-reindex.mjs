#!/usr/bin/env node
/**
 * okf-reindex.mjs — the subject layout's generated views (no dependencies).
 *
 * Usage: node okf-reindex.mjs <bundle-dir> [--check] [--json]
 *
 * A base is bridged when its okf-base.json (version 1) lists the reserved nodes
 * `claims`, `subjects` and `verdicts`, each at the path of its name and owned by
 * the sentinel 00000000-0000-0000-0000-000000000000. On a bridged base this
 * writes, deterministically, from the frontmatter of every concept:
 *   subjects/<kind>/<slug>/index.md   one section per claim type (`about:`)
 *   subjects/index.md                 the subjects by kind
 *   verdicts/index.md                 the verdict record, one line per verdict
 *   index.md                          its "## Subjects" section only
 * --check writes nothing and exits 1 when any of them differs.
 * Exit: 0 written or clean, 1 stale (--check), 2 usage or not a bridged base.
 *
 * The validator imports this module, so the views it checks are exactly the
 * ones written here, and consult parses them with the parsers below.
 */
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join, relative, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

export const SENTINEL = "00000000-0000-0000-0000-000000000000";
export const RESERVED_NODES = ["claims", "subjects", "verdicts"];
export const KINDS = { system: "System", workstream: "Workstream", project: "Project" };
export const KIND_HEADINGS = { system: "Systems", workstream: "Workstreams", project: "Projects" };
export const VERDICTS = ["rejected", "superseded", "duplicate"];
export const GENERATED_NOTE = "Generated by okf-reindex.mjs; do not edit by hand.";
const MEMBERS = "In this workstream";

// ------------------------------------------------------------- frontmatter
/** A flow list `[a, "b"]`: bare or JSON double-quoted items; null when the
 *  value is not one (nested or unbalanced brackets, an empty item). */
export function flowList(value) {
  const inner = value.slice(1, -1).trim();
  if (!inner) return [];
  const items = [], item = /\s*(?:"((?:[^"\\]|\\.)*)"|([^,"[\]]*[^,"[\]\s]))\s*(,|$)/y;
  let at = 0;
  while (at < inner.length) {
    item.lastIndex = at;
    const m = item.exec(inner);
    if (!m) return null;
    if (m[1] !== undefined) { try { items.push(JSON.parse(`"${m[1]}"`)); } catch { return null; } }
    else items.push(m[2].trim());
    at = item.lastIndex;
    if (m[3] === "," && at >= inner.length) return null;
  }
  return items;
}
/** The OKF frontmatter subset: flat `key: scalar` lines and flow lists.
 *  `listErrors` names keys whose value looks like a list but is not one. */
export function parseFrontmatter(text) {
  if (!text.startsWith("---")) return { present: false };
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---(\r?\n|$)/);
  if (!m) return { present: true, parsed: false };
  const meta = {}, listErrors = [];
  for (const line of m[1].split("\n")) {
    if (/^\s*#/.test(line) || !line.trim()) continue;
    const kv = line.match(/^([A-Za-z_][A-Za-z0-9_-]*):\s*(.*)$/);
    if (!kv) { if (!/^\s+/.test(line)) return { present: true, parsed: false }; continue; }
    const raw = kv[2].replace(/\s+#.*$/, "");
    const list = /^\[.*\]$/.test(raw.trim()) ? flowList(raw.trim()) : undefined;
    if (list === null) listErrors.push(kv[1]);
    meta[kv[1]] = Array.isArray(list) ? list : raw.replace(/^["']|["']$/g, "").trim();
  }
  return { present: true, parsed: true, meta, listErrors, body: text.slice(m[0].length) };
}

// ------------------------------------------------------------- layout
/** Whether a parsed okf-base.json declares the subject layout. All three
 *  reserved nodes, exactly; anything less is a plain version-1 base. */
export function isBridgedMeta(m) {
  if (!m || typeof m !== "object" || m.version !== 1 || !m.nodes || typeof m.nodes !== "object") return false;
  return RESERVED_NODES.every((n) => Object.hasOwn(m.nodes, n) && m.nodes[n]?.path === n && m.nodes[n]?.owner === SENTINEL);
}
export function bridged(root) {
  const file = join(root, "okf-base.json");
  if (!existsSync(file)) return false;
  try { return isBridgedMeta(JSON.parse(readFileSync(file, "utf8"))); } catch { return false; }
}
export const subjectRef = (kind, slug) => `${kind}/${slug}`;
/** subjects/<kind>/<slug>.md → { kind, slug, ref }, else null. */
export function subjectOfPath(p) {
  const m = /^subjects\/([^/]+)\/([^/]+)\.md$/.exec(p);
  return m && Object.hasOwn(KINDS, m[1]) && m[2] !== "index" && m[2] !== "log" ? { kind: m[1], slug: m[2], ref: subjectRef(m[1], m[2]) } : null;
}
export const subjectFile = (ref) => `subjects/${ref}.md`;
export const viewFile = (ref) => `subjects/${ref}/index.md`;
export const SUBJECT_REF = /^(system|workstream|project)\/[a-z0-9][a-z0-9._-]*$/;
/** Where a concept lives in the layout: a subject file, a verdict, or a claim
 *  (anything else: claims/** and every old node). */
export function place(p) {
  if (p.startsWith("subjects/")) return "subjects";
  if (p.startsWith("verdicts/")) return "verdicts";
  return "claim";
}
/** sha256 of `<Type>|<title>`, the title lowercased, trimmed and its
 *  whitespace collapsed; 16 hex. A candidate key, never an identity. */
export function titleHash(type, title) {
  const norm = String(title ?? "").toLowerCase().trim().replace(/\s+/g, " ");
  return createHash("sha256").update(`${String(type ?? "").trim()}|${norm}`).digest("hex").slice(0, 16);
}

// ------------------------------------------------------------- render
const one = (s) => String(s ?? "").replace(/\s+/g, " ").trim();
// Brackets would end the link text for every reader's link pattern (the 5.8
// validator's included), leaving the claim unlinked: shown as parentheses.
const linkText = (s) => one(s).replace(/\[/g, "(").replace(/\]/g, ")");
function entry(title, path, description) {
  if (/[\s()<>]/.test(path)) throw Object.assign(new Error(`${path}: a path with spaces, parentheses or angle brackets cannot be linked from a generated index`), { code: "E_PATH" });
  const d = one(description);
  return `* [${linkText(title)}](/${path})${d ? ` - ${d}` : ""}`;
}
const fallbackTitle = (p) => p.split("/").pop().replace(/\.md$/, "");
const byText = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

/** Every generated file's expected content, from the concepts' frontmatter
 *  (`concepts`: Map of base path → meta, reserved files excluded) and the
 *  current root index.md text. → Map of base path → text. */
export function generate(concepts, rootIndex = "") {
  const subjects = new Map();
  for (const [p, meta] of concepts) {
    const s = subjectOfPath(p);
    if (s) subjects.set(s.ref, { ...s, path: p, meta: meta || {} });
  }
  const out = new Map();
  // Subject views.
  const claimsOf = new Map([...subjects.keys()].map((ref) => [ref, []]));
  for (const [p, meta] of [...concepts].sort(([a], [b]) => byText(a, b))) {
    if (place(p) !== "claim" || !Array.isArray(meta?.about)) continue;
    for (const ref of new Set(meta.about)) if (claimsOf.has(ref)) claimsOf.get(ref).push({ path: p, meta });
  }
  const order = (ref) => Object.keys(KINDS).indexOf(ref.split("/")[0]);
  const sortedRefs = [...subjects.keys()].sort((a, b) => order(a) - order(b) || byText(a, b));
  for (const ref of sortedRefs) {
    const s = subjects.get(ref), title = one(s.meta.title) || s.slug;
    const lines = [`# ${title}`, ""];
    if (one(s.meta.description)) lines.push(one(s.meta.description), "");
    lines.push(GENERATED_NOTE, `Subject file: [${linkText(title)}](/${s.path})`, "");
    if (s.kind === "workstream") {
      const members = sortedRefs.filter((r) => r !== ref && Array.isArray(subjects.get(r).meta["in-workstreams"]) && subjects.get(r).meta["in-workstreams"].includes(ref));
      if (members.length) {
        lines.push(`## ${MEMBERS}`, "");
        for (const r of members) lines.push(entry(one(subjects.get(r).meta.title) || subjects.get(r).slug, subjects.get(r).path, subjects.get(r).meta.description));
        lines.push("");
      }
    }
    const types = new Map();
    for (const c of claimsOf.get(ref)) {
      const type = one(c.meta.type) || "Untyped", kind = typeof c.meta.kind === "string" ? one(c.meta.kind) : "";
      if (!types.has(type)) types.set(type, new Map());
      const kinds = types.get(type);
      if (!kinds.has(kind)) kinds.set(kind, []);
      kinds.get(kind).push(entry(one(c.meta.title) || fallbackTitle(c.path), c.path, c.meta.description));
    }
    if (!types.size) lines.push("No claims are about this subject yet.", "");
    for (const type of [...types.keys()].sort(byText)) {
      lines.push(`## ${type}`, "");
      const kinds = types.get(type);
      if (kinds.has("")) lines.push(...kinds.get(""), "");
      for (const kind of [...kinds.keys()].filter(Boolean).sort(byText)) lines.push(`### ${kind}`, "", ...kinds.get(kind), "");
    }
    out.set(viewFile(ref), lines.join("\n").replace(/\n+$/, "") + "\n");
  }
  // subjects/index.md
  const idx = ["# Subjects", "", `${GENERATED_NOTE} What this base's knowledge is about, by kind. Each subject's claims are listed in its generated index, \`subjects/<kind>/<slug>/index.md\`.`, ""];
  for (const kind of Object.keys(KINDS)) {
    const refs = sortedRefs.filter((r) => subjects.get(r).kind === kind);
    if (!refs.length) continue;
    idx.push(`## ${KIND_HEADINGS[kind]}`, "", ...refs.map((r) => entry(one(subjects.get(r).meta.title) || subjects.get(r).slug, subjects.get(r).path, subjects.get(r).meta.description)), "");
  }
  if (!subjects.size) idx.push("No subjects yet.", "");
  out.set("subjects/index.md", idx.join("\n").replace(/\n+$/, "") + "\n");
  // verdicts/index.md
  const verdicts = [...concepts].filter(([p]) => place(p) === "verdicts").sort(([a], [b]) => byText(a, b));
  const vidx = ["# Verdicts", "", `${GENERATED_NOTE} The knowledge maintainer's record of the claims it rejected, superseded or closed as duplicates, one line each: verdict; claim type; title hash; claim description. \`oats okf verdicts --check <claim file>\` reads it.`, ""];
  for (const [p, meta] of verdicts) {
    const fields = [one(meta?.verdict), one(meta?.["claim-type"]), one(meta?.["title-hash"]), one(meta?.["claim-description"])];
    vidx.push(entry(one(meta?.["claim-title"]) || fallbackTitle(p), p, fields.join("; ")));
  }
  if (!verdicts.length) vidx.push("No verdicts yet.");
  out.set("verdicts/index.md", vidx.join("\n").replace(/\n+$/, "") + "\n");
  out.set("index.md", withSubjectsSection(rootIndex));
  return out;
}
export const ROOT_SECTION = "## Subjects\n\n* [Subjects](subjects/index.md) - What this base's knowledge is about, by kind; each subject has a generated index of its claims.\n";
/** The root index.md with its "## Subjects" section (heading to the next
 *  `## ` heading or the end) replaced by the generated one, or appended. */
export function withSubjectsSection(text) {
  const lines = String(text ?? "").replace(/\r\n/g, "\n").split("\n");
  const start = lines.findIndex((l) => /^## Subjects\s*$/.test(l));
  let before, after;
  if (start < 0) { before = lines.join("\n"); after = ""; }
  else {
    let end = lines.findIndex((l, i) => i > start && /^## /.test(l));
    if (end < 0) end = lines.length;
    before = lines.slice(0, start).join("\n");
    after = lines.slice(end).join("\n");
  }
  before = before.replace(/\n+$/, "");
  after = after.replace(/^\n+/, "").replace(/\n+$/, "");
  return `${before ? `${before}\n\n` : ""}${ROOT_SECTION}${after ? `\n${after}\n` : ""}`;
}

// ------------------------------------------------------------- parse (consult)
const ENTRY = /^\* \[([^\]]*)\]\(\/([^)\s]+)\)(?: - (.*))?$/;
export function parseEntry(line) {
  const m = ENTRY.exec(line);
  return m ? { title: m[1], path: m[2], description: m[3] ?? "" } : null;
}
/** A generated subject view → { title, description, members, sections:
 *  [{ type, kind, entries }] } (kind null for entries directly under a type). */
export function parseView(text) {
  const lines = String(text).split(/\r?\n/), out = { title: "", description: "", members: [], sections: [] };
  let type = null, kind = null, inMembers = false, sawNote = false;
  for (const line of lines) {
    if (!out.title && line.startsWith("# ")) { out.title = line.slice(2).trim(); continue; }
    if (line.startsWith(GENERATED_NOTE)) { sawNote = true; continue; }
    if (!sawNote && out.title && line.trim() && !line.startsWith("#")) { out.description = line.trim(); continue; }
    const h2 = /^## (.+)$/.exec(line), h3 = /^### (.+)$/.exec(line);
    if (h2) { inMembers = h2[1].trim() === MEMBERS; type = inMembers ? null : h2[1].trim(); kind = null; continue; }
    if (h3) { kind = h3[1].trim(); continue; }
    const e = parseEntry(line);
    if (!e) continue;
    if (inMembers) out.members.push(e);
    else if (type) {
      let section = out.sections.find((s) => s.type === type && s.kind === kind);
      if (!section) out.sections.push(section = { type, kind, entries: [] });
      section.entries.push(e);
    }
  }
  return out;
}
/** Claim counts by type from a parsed view, in view order. */
export function counts(view) {
  const out = new Map();
  for (const s of view.sections) out.set(s.type, (out.get(s.type) ?? 0) + s.entries.length);
  return out;
}
/** subjects/index.md → [{ ref, kind, slug, title, description }]. */
export function parseSubjectsIndex(text) {
  const out = [];
  for (const line of String(text).split(/\r?\n/)) {
    const e = parseEntry(line), s = e && subjectOfPath(e.path);
    if (s) out.push({ ref: s.ref, kind: s.kind, slug: s.slug, title: e.title, description: e.description });
  }
  return out;
}
/** verdicts/index.md → [{ id, path, title, verdict, claimType, titleHash, description }]. */
export function parseVerdictsIndex(text) {
  const out = [];
  for (const line of String(text).split(/\r?\n/)) {
    const e = parseEntry(line), m = e && /^verdicts\/([^/]+)\.md$/.exec(e.path);
    if (!m) continue;
    const [verdict = "", claimType = "", hash = "", ...rest] = e.description.split("; ");
    out.push({ id: m[1], path: e.path, title: e.title, verdict, claimType, titleHash: hash, description: rest.join("; ") });
  }
  return out;
}

// ------------------------------------------------------------- files
/** Every .md file under root (dot entries skipped), as base paths. */
export function markdownFiles(root) {
  const files = [];
  (function walk(d) {
    for (const e of readdirSync(d, { withFileTypes: true })) {
      if (e.name.startsWith(".")) continue;
      const p = join(d, e.name);
      if (e.isDirectory()) walk(p);
      else if (e.name.endsWith(".md")) files.push(relative(root, p).split("\\").join("/"));
    }
  })(root);
  return files.sort(byText);
}
export const isReservedFile = (p) => ["index.md", "log.md"].includes(p.split("/").pop());
/** The concepts' frontmatter (reserved files excluded). */
export function readConcepts(root) {
  const concepts = new Map();
  for (const p of markdownFiles(root)) {
    if (isReservedFile(p)) continue;
    const fm = parseFrontmatter(readFileSync(join(root, p), "utf8"));
    concepts.set(p, fm.parsed ? fm.meta : {});
  }
  return concepts;
}
/** Generated view files on disk that no subject file backs any more. */
export function orphanViews(root, concepts) {
  const out = [];
  for (const p of markdownFiles(root)) {
    const m = /^subjects\/([^/]+)\/([^/]+)\/index\.md$/.exec(p);
    if (m && Object.hasOwn(KINDS, m[1]) && !concepts.has(`subjects/${m[1]}/${m[2]}.md`)) out.push(p);
  }
  return out;
}
const readOr = (file) => (existsSync(file) ? readFileSync(file, "utf8") : null);
/** What --check reports: [{ path, status: missing | stale | orphan }]. */
export function staleViews(root, concepts = readConcepts(root)) {
  const expected = generate(concepts, readOr(join(root, "index.md")) ?? "");
  const out = [];
  for (const [p, text] of expected) {
    const have = readOr(join(root, p));
    if (have === null) out.push({ path: p, status: "missing" });
    else if (have !== text) out.push({ path: p, status: "stale" });
  }
  for (const p of orphanViews(root, concepts)) out.push({ path: p, status: "orphan" });
  return out;
}

function main(argv) {
  const check = argv.includes("--check"), asJson = argv.includes("--json");
  const dir = argv.find((a) => !a.startsWith("--"));
  const unknown = argv.filter((a) => a.startsWith("--") && !["--check", "--json"].includes(a));
  if (!dir || !existsSync(dir) || unknown.length) { console.error("usage: okf-reindex.mjs <bundle-dir> [--check] [--json]"); return 2; }
  const root = resolve(dir);
  if (!bridged(root)) {
    const message = `${root} has no subject layout: okf-base.json does not list the reserved nodes ${RESERVED_NODES.join(", ")} (owner ${SENTINEL})`;
    if (asJson) console.log(JSON.stringify({ bundle: root, bridged: false, error: message })); else console.error(message);
    return 2;
  }
  let concepts, stale;
  try { concepts = readConcepts(root); stale = staleViews(root, concepts); }
  catch (e) { console.error(`okf-reindex: ${e.message}`); return 2; }
  if (!check) {
    const expected = generate(concepts, readOr(join(root, "index.md")) ?? "");
    for (const s of stale) {
      const file = join(root, s.path);
      if (s.status === "orphan") {
        rmSync(file);
        try { if (!readdirSync(dirname(file)).length) rmSync(dirname(file), { recursive: true }); } catch { /* best effort */ }
      } else { mkdirSync(dirname(file), { recursive: true }); writeFileSync(file, expected.get(s.path)); }
    }
  }
  if (asJson) console.log(JSON.stringify({ bundle: root, bridged: true, check, changed: stale }, null, 2));
  else {
    console.log(`OKF reindex — ${root}`);
    for (const s of stale) console.log(`  ${check ? s.status.padEnd(7) : (s.status === "orphan" ? "removed" : "wrote  ")} ${s.path}`);
    console.log(stale.length ? (check ? `STALE — ${stale.length} generated file(s) differ; run okf-reindex.mjs ${dir}` : `wrote ${stale.length} file(s)`) : "clean — generated indexes are current");
  }
  return check && stale.length ? 1 : 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = main(process.argv.slice(2));
