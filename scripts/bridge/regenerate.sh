#!/bin/sh
# Regenerate the bridge PR branch from the then-current main (spec §3: rerun the conversion, never rebase by
# hand). Run inside a clone of oats-knowledge on the PR branch:
#
#   scripts/bridge/regenerate.sh <oats-okf checkout> <PR number> <CI adapter commit>
#
# Leaves the branch as two commits on origin/main: the generated bridge, then the CI adapter commit
# re-applied. Runs --check and verify.mjs; push with `git push --force-with-lease`.
set -eu
OKF=$(cd "$1" && pwd); PR=$2; ADAPTER=$(git rev-parse --verify "$3^{commit}")
BRANCH=$(git rev-parse --abbrev-ref HEAD)
test -z "$(git status --porcelain)" || { echo "working tree not clean" >&2; exit 1; }
git fetch -q origin main
BASE=$(git rev-parse --short=7 origin/main)
git switch -q --detach origin/main
REF="PR [#$PR](https://github.com/oats-project/oats-knowledge/pull/$PR)"
node "$OKF/scripts/bridge/bridge.mjs" . --pr "$REF" > /dev/null
node "$OKF/scripts/bridge/bridge.mjs" . --pr "$REF" --check
node "$OKF/scripts/bridge/verify.mjs" . origin/main > /dev/null
git add knowledge
git commit -q -m "Bridge: subjects, about-edges, ids and generated subject views on the version-1 layout

Generated by scripts/bridge/bridge.mjs (oats-okf) from main at $BASE: the reserved
nodes claims, subjects and verdicts (placeholder owner), the subject files and their
generated views, and about/kind/id frontmatter inserted after each concept's
description line. No file moved; no concept body changed."
git cherry-pick "$ADAPTER" > /dev/null
git branch -f "$BRANCH" HEAD
git switch -q "$BRANCH"
echo "regenerated $BRANCH on $BASE: $(git log --oneline -2 | tr '\n' ' ')"
