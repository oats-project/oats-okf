#!/bin/sh
# Regenerate the bridge PR branch from the then-current main (spec §3: rerun the conversion, never rebase by
# hand). Run inside a clone of oats-knowledge on the PR branch:
#
#   scripts/bridge/regenerate.sh <oats-okf checkout> <PR number> <CI adapter commit> <okf-reindex.mjs> <its commit>
#
# <okf-reindex.mjs> is oats.okf 6.0's regenerator; it writes the views. <its commit> is cited in the message.
#
# Leaves the branch as two commits on origin/main: the generated bridge, then the CI adapter commit
# re-applied. Runs --check and verify.mjs; push with `git push --force-with-lease`.
set -eu
[ $# -eq 5 ] || { echo "usage: regenerate.sh <oats-okf checkout> <PR number> <CI adapter commit> <okf-reindex.mjs> <its commit>" >&2; exit 2; }
OKF=$(cd "$1" && pwd); PR=$2; ADAPTER=$(git rev-parse --verify "$3^{commit}")
REINDEX=$(cd "$(dirname "$4")" && pwd)/$(basename "$4"); CITE=$5
test -f "$REINDEX" || { echo "no regenerator at $4" >&2; exit 2; }
case "$PR" in *[!0-9]*|'') echo "PR must be a number" >&2; exit 2;; esac
BRANCH=$(git rev-parse --abbrev-ref HEAD)
test -z "$(git status --porcelain)" || { echo "working tree not clean" >&2; exit 1; }
# Fetch main's tip explicitly (a branch-limited fetch refspec would leave origin/main stale) and use that
# exact commit for generation, verification and the recorded base.
git fetch -q origin +refs/heads/main:refs/remotes/origin/main
MAIN=$(git rev-parse --verify FETCH_HEAD^{commit})
[ "$MAIN" = "$(git rev-parse --verify refs/remotes/origin/main)" ] || { echo "origin/main did not update to the fetched tip" >&2; exit 1; }
# On any failure after this point, return to the branch (the tree was clean; only generated files are lost).
trap 'rc=$?; set +e; if [ $rc -ne 0 ]; then git cherry-pick --abort >/dev/null 2>&1; git checkout -q -f "$BRANCH"; echo "regenerate failed; back on $BRANCH" >&2; fi; exit $rc' EXIT
BASE=$(git rev-parse --short=7 "$MAIN")
git switch -q --detach "$MAIN"
REF="PR [#$PR](https://github.com/oats-project/oats-knowledge/pull/$PR)"
node "$OKF/scripts/bridge/bridge.mjs" . --pr "$REF" --reindex "$REINDEX" > /dev/null
node "$OKF/scripts/bridge/bridge.mjs" . --pr "$REF" --reindex "$REINDEX" --check
node "$OKF/scripts/bridge/verify.mjs" . "$MAIN" > /dev/null
git add knowledge
git commit -q -m "Bridge: subjects, about-edges, ids and generated subject views on the version-1 layout

Generated by scripts/bridge/bridge.mjs (oats-okf) from main at $BASE: the reserved
nodes claims, subjects and verdicts (placeholder owner), the subject files and their
generated views, and about/kind/id frontmatter inserted after each concept's
description line. No file moved; no concept body changed.
Views written by okf-reindex.mjs (oats.okf 6.0 subject layer, $CITE)."
git cherry-pick "$ADAPTER" > /dev/null
git branch -f "$BRANCH" HEAD
git switch -q "$BRANCH"
echo "regenerated $BRANCH on $BASE: $(git log --oneline -2 | tr '\n' ' ')"
